fun updateAppLocale(language: String, context: Context) {
    val locale = if (language.startsWith("Indo", ignoreCase = true)) Locale("id", "ID") else Locale.ENGLISH
    Locale.setDefault(locale)
    val resources = context.resources
    val config = resources.configuration
    config.setLocale(locale)
    try {
        context.createConfigurationContext(config)
    } catch (_: Exception) {}
}
